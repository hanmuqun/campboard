"""Push the local snapshot into Cloudflare D1.

The Python side stays the only thing that talks to Recreation.gov; this is the
one-way door from the local JSON into the database the website reads.

    python push_d1.py            # remote
    python push_d1.py --local    # local wrangler sqlite, for testing
"""
import argparse
import json
import shutil
import subprocess
import sys
from pathlib import Path

sys.stdout.reconfigure(encoding="utf-8")

ROOT = Path(__file__).resolve().parent
DATA = ROOT / "data"
WEB = ROOT / "web"
WRANGLER = WEB / "node_modules" / "wrangler" / "bin" / "wrangler.js"
DB = "campboard"


def wrangler_cmd():
    """Local install if present, otherwise the CLI over npx (used in CI)."""
    if WRANGLER.exists():
        node = shutil.which("node") or r"C:\Program Files\nodejs\node.exe"
        return [node, str(WRANGLER)]
    return ["npx", "-y", "wrangler@4.162.0"]


def q(value):
    """SQL literal, or NULL."""
    if value is None:
        return "NULL"
    if isinstance(value, (int, float)):
        return str(value)
    return "'" + str(value).replace("'", "''") + "'"


def build_sql(snapshot, changes):
    out = ["-- generated by push_d1.py", "DELETE FROM campgrounds;"]
    for c in snapshot["campgrounds"]:
        out.append(
            "INSERT INTO campgrounds (id,name,park,city,state,url,sites,days,updated_at) VALUES ("
            + ",".join(
                [
                    q(c["id"]),
                    q(c["name"]),
                    q(c["park"]),
                    q(c.get("city")),
                    q(c.get("state")),
                    q(c.get("url")),
                    q(c.get("sites")),
                    q(json.dumps(c["days"], separators=(",", ":"))),
                    q(snapshot["generated"]),
                ]
            )
            + ");"
        )

    for e in changes:
        out.append(
            "INSERT OR IGNORE INTO changes (ts,camp_id,name,park,date,kind,before,after,delta) VALUES ("
            + ",".join(
                [
                    q(e["ts"]),
                    q(e["id"]),
                    q(e["name"]),
                    q(e["park"]),
                    q(e["date"]),
                    q(e["kind"]),
                    q(e["before"]),
                    q(e["after"]),
                    q(e.get("delta")),
                ]
            )
            + ");"
        )

    out.append(
        "INSERT INTO meta (k,v) VALUES ('generated',"
        + q(snapshot["generated"])
        + ") ON CONFLICT(k) DO UPDATE SET v=excluded.v;"
    )
    return "\n".join(out) + "\n"


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--local", action="store_true", help="push to the local sqlite instead of the remote D1")
    ap.add_argument("--dry-run", action="store_true", help="write the SQL but do not execute")
    args = ap.parse_args()

    snapshot = json.loads((DATA / "snapshot.json").read_text(encoding="utf-8"))
    changes_path = DATA / "changes.json"
    changes = json.loads(changes_path.read_text(encoding="utf-8")) if changes_path.exists() else []

    sql = build_sql(snapshot, changes)
    sql_path = DATA / "push.sql"
    sql_path.write_text(sql, encoding="utf-8")
    print(f"wrote {sql_path.name}: {len(snapshot['campgrounds'])} campgrounds, {len(changes)} changes, {len(sql)} bytes")

    if args.dry_run:
        return

    cmd = [
        *wrangler_cmd(),
        "d1",
        "execute",
        DB,
        "--file",
        str(sql_path),
        "--yes",
    ]
    if args.local:
        cmd.append("--local")
    else:
        cmd.append("--remote")

    result = subprocess.run(cmd, cwd=str(WEB), capture_output=True, text=True, encoding="utf-8", errors="replace")
    tail = (result.stdout or "")[-400:]
    if result.returncode != 0:
        print("D1 push FAILED", file=sys.stderr)
        print((result.stderr or "")[-1500:], file=sys.stderr)
        sys.exit(1)
    print("D1 push ok")
    if "--local" in cmd:
        print(tail.strip())


if __name__ == "__main__":
    main()
